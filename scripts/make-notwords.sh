#!/bin/sh
# Writes the list of real words a blob name must never be (<version folder>/js/notwords.js; default prototype/v9).
# Source: the system dictionary (macOS /usr/share/dict/words), filtered to the shape of a blob name: CVCV plus an optional soft ending.
set -e
cd "$(dirname "$0")/.."
out=${1:-prototype/v9}/js/notwords.js
words=$(grep -E '^[ptkmnbdlrvsfg][aeiou][ptkmnbdlrvsfg][aeiou][nmlrs]?$' /usr/share/dict/words | sort -u | tr '\n' ' ' | sed 's/ $//')
{
  echo "// Generated by scripts/make-notwords.sh from the system dictionary: real words shaped like a blob name. Do not edit by hand."
  echo "export const NOT_WORDS = new Set('$words'.split(' '));"
} > "$out"
echo "wrote $out ($(echo "$words" | wc -w | tr -d ' ') words)"
